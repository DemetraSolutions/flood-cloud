/**
 * Types of the backend REST contract (`doc/API-Guidelines.md` sections 3-5).
 * They mirror the standard response envelopes of the `/v1` surface.
 */

/** Error codes returned by the backend (`doc/API-Guidelines.md` section 5). */
export const API_ERROR_CODES = [
  'MALFORMED_JSON',
  'BAD_REQUEST',
  'UNAUTHENTICATED',
  'TOKEN_EXPIRED',
  'CLOCK_SKEW',
  'FORBIDDEN',
  'NOT_FOUND',
  'METHOD_NOT_ALLOWED',
  'CONFLICT',
  'PRECONDITION_FAILED',
  'PAYLOAD_TOO_LARGE',
  'UNSUPPORTED_MEDIA_TYPE',
  'VALIDATION_ERROR',
  'RATE_LIMITED',
  'QUOTA_EXCEEDED',
  'INTERNAL_ERROR',
  'SERVICE_UNAVAILABLE',
] as const;

/** Union of the error codes returned by the backend. */
export type ApiErrorCode = (typeof API_ERROR_CODES)[number];

/** Codes generated by the client, never sent by the backend. */
export const CLIENT_ERROR_CODES = ['NETWORK_ERROR', 'UNKNOWN_ERROR'] as const;

/** Union of the client-generated error codes. */
export type ClientErrorCode = (typeof CLIENT_ERROR_CODES)[number];

/** Single-resource response envelope. */
export type ApiData<T> = { data: T };

/** Cursor-paginated collection response envelope. */
export type ApiPage<T> = { data: T[]; page: { limit: number; next: string | null } };

/** Per-field validation detail carried by `422` responses. */
export type ApiErrorDetail = { field: string; issue: string };

/** Standard error envelope. */
export type ApiErrorBody = {
  error: { code: ApiErrorCode; message: string; details?: ApiErrorDetail[] };
};
