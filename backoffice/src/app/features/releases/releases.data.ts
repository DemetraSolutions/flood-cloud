/** Base URL of the release archives, published on the external Demetra Solutions site. */
export const RELEASES_DOWNLOAD_BASE_URL = 'https://www.demetrasolutions.com/APPS/RELEASES';

/** Hotfix applied to a release after its publication. */
export interface ReleaseHotfix {
  /** Progressive number of the hotfix. */
  readonly number: number;
  /** Date of the hotfix (`YYYY-MM-DD`). */
  readonly date: string;
}

/** One version of the point-of-sale app, with its release notes (product content in Italian). */
export interface Release {
  /** Version, e.g. `1.20.0` or `0.1.0-beta-3`. */
  readonly version: string;
  /** Release date (`YYYY-MM-DD`), `null` for the oldest versions, which the notes never dated. */
  readonly date: string | null;
  /** Latest hotfix of the version, when there is one. */
  readonly hotfix?: ReleaseHotfix;
  /** Whether an archive is published for the version (the link points to the external site). */
  readonly downloadable: boolean;
  /** New features and improvements. */
  readonly features: readonly string[];
  /** Fixes. */
  readonly fixes: readonly string[];
  /** Notices to read before installing (paragraphs). */
  readonly notes?: readonly string[];
}

/**
 * URL of the archive of a version, built as the legacy backoffice did.
 *
 * @param version Version of the release, e.g. `1.20.0`.
 * @returns The external download URL.
 */
export function releaseDownloadUrl(version: string): string {
  return `${RELEASES_DOWNLOAD_BASE_URL}/Flood_${version}.zip`;
}

